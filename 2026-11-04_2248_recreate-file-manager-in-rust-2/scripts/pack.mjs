// Packs the wasm-bindgen output into ES modules that vite can inline into a single index.html.
//   target/web/smart_egui.js      -> src/glue.js   (patched: no file://-style wasm lookup)
//   target/web/smart_egui_bg.wasm -> src/wasm.js   (gzip + base64, decoded at runtime)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const root = new URL('..', import.meta.url).pathname;
const inDir = process.argv[2] || `${root}target/web`;
let glue = readFileSync(`${inDir}/smart_egui.js`, 'utf8');
// we always pass the wasm bytes explicitly, so drop the URL-based lookup
glue = glue.replace(/module_or_path = new URL\([^)]*\);/g, "throw new Error('wasm bytes missing');");
glue = `// Generated by scripts/pack.mjs — wasm-bindgen glue for smart-egui.\n${glue}`;
writeFileSync(`${root}src/glue.js`, glue);

const wasm = readFileSync(`${inDir}/smart_egui_bg.wasm`);
const gz = gzipSync(wasm, { level: 9 });
writeFileSync(`${root}src/wasm.js`, `// Generated by scripts/pack.mjs — gzip + base64 of smart_egui_bg.wasm.\nexport default "${gz.toString('base64')}";\n`);
console.log(`wasm ${(wasm.length / 1e6).toFixed(2)} MB -> gzip ${(gz.length / 1e6).toFixed(2)} MB -> base64 ${(gz.length * 1.34 / 1e6).toFixed(2)} MB`);
