//! Build tooling for Smart Files, written in Rust so the whole pipeline stays JS-free.
//!
//!   cargo run -p xtask --release -- assets   rasterise icons, synthesise demo audio, make wallpapers, copy fonts/thumbs
//!   cargo run -p xtask --release -- bundle   wasm-bindgen output -> ONE self-contained ../index.html (wasm embedded)
//!
//! The HTML shell below is *generated* here (it is the standard wasm-bindgen bootstrap: decode wasm, call `start`).
use std::{fs, path::{Path, PathBuf}, process::Command};

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().unwrap()
}

fn main() {
    let cmd = std::env::args().nth(1).unwrap_or_default();
    match cmd.as_str() {
        "assets" => assets(),
        "bundle" => bundle(),
        _ => eprintln!("usage: xtask assets|bundle"),
    }
}

// ───────────────────────────────────────────── assets ─────────────────────────────────────────────

fn assets() {
    let r = root();
    let a = r.join("assets");
    fs::create_dir_all(a.join("icons")).unwrap();
    fs::create_dir_all(a.join("fonts")).unwrap();
    fs::create_dir_all(a.join("audio")).unwrap();
    fonts(&a);
    icons(&r, &a);
    audio(&a);
    wallpapers(&a);
}

fn fonts(a: &Path) {
    // Inter (UI) + JetBrains Mono (system mono) live in assets/fonts (checked in)
    for f in ["Inter-regular.otf", "JBMono-bold.ttf"] {
        assert!(a.join("fonts").join(f).exists(), "missing font {f}");
    }
}

fn icons(r: &Path, a: &Path) {
    let json = std::env::var("SOLAR_JSON").unwrap_or("/tmp/ic/node_modules/@iconify-json/solar/icons.json".into());
    let data: serde_json::Value = serde_json::from_str(&fs::read_to_string(&json).expect("SOLAR_JSON (npm i @iconify-json/solar)")).unwrap();
    let find = |n: &str| -> Option<String> {
        if let Some(i) = data["icons"].get(n) {
            return i["body"].as_str().map(String::from);
        }
        let p = data["aliases"].get(n)?["parent"].as_str()?;
        data["icons"][p]["body"].as_str().map(String::from)
    };
    let list = fs::read_to_string(a.join("icon_names.txt")).unwrap();
    let mut gen = String::from("// @generated by `cargo run -p xtask -- assets` from assets/icon_names.txt — do not edit\npub fn bytes(name: &str, v: u8) -> Option<&'static [u8]> {\n    Some(match (name, v) {\n");
    let mut count = 0;
    for line in list.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let (name, src) = line.split_once('=').unwrap_or((line, line));
        for (code, suffix) in [('o', "linear"), ('d', "bold-duotone"), ('f', "bold")] {
            let Some(body) = find(&format!("{src}-{suffix}")) else {
                eprintln!("icon missing: {src}-{suffix}");
                continue;
            };
            let svg = format!(
                r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="128" height="128">{}</svg>"#,
                body.replace("currentColor", "#ffffff")
            );
            let tree = resvg::usvg::Tree::from_str(&svg, &resvg::usvg::Options::default()).expect("svg");
            let mut pm = resvg::tiny_skia::Pixmap::new(128, 128).unwrap();
            resvg::render(&tree, resvg::tiny_skia::Transform::identity(), &mut pm.as_mut());
            pm.save_png(a.join(format!("icons/{name}_{code}.png"))).unwrap();
            gen.push_str(&format!("        (\"{name}\", b'{code}') => include_bytes!(\"../../../../assets/icons/{name}_{code}.png\"),\n"));
            count += 1;
        }
    }
    gen.push_str("        _ => return None,\n    })\n}\n");
    fs::write(r.join("crates/smart-desktop/src/ui/icons_gen.rs"), gen).unwrap();
    println!("icons: {count} rasters");
}

struct Rng(u32);
impl Rng {
    fn next(&mut self) -> f32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 17;
        self.0 ^= self.0 << 5;
        (self.0 as f32 / u32::MAX as f32) * 2.0 - 1.0
    }
}

// Tiny additive synth so the demo library has real, playable audio.
fn audio(a: &Path) {
    const SR: u32 = 22_050;
    let tau = std::f32::consts::TAU;
    let put = |name: &str, secs: f32, f: &mut dyn FnMut(f32) -> f32| {
        let n = (SR as f32 * secs) as usize;
        let mut pcm = Vec::with_capacity(n * 2);
        for i in 0..n {
            let t = i as f32 / SR as f32;
            let fade = (1.0 - t / secs).clamp(0.0, 1.0).min(t * 200.0).min(1.0);
            let v = (f(t) * fade).clamp(-1.0, 1.0);
            pcm.extend_from_slice(&((v * 26000.0) as i16).to_le_bytes());
        }
        let mut w = Vec::new();
        w.extend_from_slice(b"RIFF");
        w.extend_from_slice(&(36 + pcm.len() as u32).to_le_bytes());
        w.extend_from_slice(b"WAVEfmt ");
        w.extend_from_slice(&16u32.to_le_bytes());
        w.extend_from_slice(&1u16.to_le_bytes());
        w.extend_from_slice(&1u16.to_le_bytes());
        w.extend_from_slice(&SR.to_le_bytes());
        w.extend_from_slice(&(SR * 2).to_le_bytes());
        w.extend_from_slice(&2u16.to_le_bytes());
        w.extend_from_slice(&16u16.to_le_bytes());
        w.extend_from_slice(b"data");
        w.extend_from_slice(&(pcm.len() as u32).to_le_bytes());
        w.extend_from_slice(&pcm);
        fs::write(a.join(format!("audio/{name}.wav")), w).unwrap();
    };
    let beat = 60.0 / 126.0;
    put("kick_logdrum", 3.8, &mut |t| {
        let tt = t % beat;
        let f = 58.0 + 90.0 * (-tt * 28.0).exp();
        ((tt * f * tau).sin() * (-tt * 5.0).exp()) * 0.95 + (tau * 2.0 * f * tt).sin() * 0.15 * (-tt * 14.0).exp()
    });
    put("logdrum_conga", 3.2, &mut |t| {
        let step = beat / 2.0;
        let tt = t % step;
        let base = [196.0f32, 247.0, 220.0, 294.0][(t / step) as usize % 4];
        (tt * base * tau).sin() * (-tt * 11.0).exp() * 0.8
    });
    let mut rng = Rng(0x9e3779b9);
    put("shaker", 3.0, &mut |t| {
        let step = beat / 4.0;
        let tt = t % step;
        rng.next() * (-tt * 38.0).exp() * if ((t / step) as i32) % 2 == 0 { 0.7 } else { 0.4 }
    });
    put("pad_warm", 4.0, &mut |t| {
        let mut s = 0.0;
        for (k, f) in [220.0f32, 277.2, 329.6, 440.0].iter().enumerate() {
            s += (t * f * tau + (t * 0.5 + k as f32).sin() * 0.4).sin() * 0.18;
            s += (t * f * 1.004 * tau).sin() * 0.1;
        }
        s * (0.6 + 0.4 * (t * 0.7).sin())
    });
    put("piano_lead", 3.6, &mut |t| {
        let notes = [523.25f32, 659.25, 587.33, 783.99, 659.25, 523.25, 587.33, 440.0];
        let d = 0.45;
        let tt = t % d;
        let f = notes[((t / d) as usize) % notes.len()];
        ((tt * f * tau).sin() + 0.4 * (tt * f * 2.0 * tau).sin() + 0.15 * (tt * f * 3.0 * tau).sin()) * (-tt * 4.5).exp() * 0.5
    });
    put("bass_deep", 3.4, &mut |t| {
        let notes = [55.0f32, 55.0, 65.4, 49.0];
        let d = 0.85;
        let tt = t % d;
        (tt * notes[((t / d) as usize) % 4] * tau).sin() * (-tt * 1.8).exp() * 0.9
    });
    println!("audio: 6 wavs");
}

fn wallpapers(a: &Path) {
    use image::{imageops, Rgb, RgbImage};
    let (w, h) = (1600u32, 1000u32);
    let mk = |name: &str, stops: [[f32; 3]; 3], blobs: &[(f32, f32, f32, [f32; 3])]| {
        let mut img = RgbImage::new(w, h);
        for y in 0..h {
            for x in 0..w {
                let (u, v) = (x as f32 / w as f32, y as f32 / h as f32);
                let t = (u * 0.35 + v * 0.65).clamp(0.0, 1.0);
                let (c0, c1, tt) = if t < 0.5 { (stops[0], stops[1], t * 2.0) } else { (stops[1], stops[2], (t - 0.5) * 2.0) };
                let mut c = [0.0f32; 3];
                for k in 0..3 {
                    c[k] = c0[k] + (c1[k] - c0[k]) * tt;
                }
                for (bx, by, br, bc) in blobs {
                    let d = (((u - bx) * 1.6).powi(2) + (v - by).powi(2)).sqrt() / br;
                    let m = (1.0 - d).clamp(0.0, 1.0).powi(2) * 0.8;
                    for k in 0..3 {
                        c[k] += (bc[k] - c[k]) * m;
                    }
                }
                let grain = (((x * 7919 + y * 104729) % 97) as f32 / 97.0 - 0.5) * 2.0;
                img.put_pixel(x, y, Rgb([0, 1, 2].map(|k| ((c[k] + grain * 0.6) as i32).clamp(0, 255) as u8)));
            }
        }
        save_jpg(&img, &a.join(format!("{name}.jpg")), 82);
        let small = imageops::resize(&img, 480, 300, imageops::FilterType::Triangle);
        save_jpg(&imageops::blur(&small, 14.0), &a.join(format!("{name}_blur.jpg")), 80);
    };
    mk("wallpaper_dusk", [[34.0, 28.0, 66.0], [96.0, 56.0, 120.0], [232.0, 132.0, 120.0]], &[(0.8, 0.85, 0.6, [255.0, 186.0, 120.0]), (0.15, 0.2, 0.5, [70.0, 90.0, 200.0])]);
    mk("wallpaper_meadow", [[28.0, 66.0, 70.0], [70.0, 130.0, 96.0], [196.0, 214.0, 130.0]], &[(0.25, 0.8, 0.55, [226.0, 232.0, 150.0]), (0.85, 0.15, 0.5, [60.0, 150.0, 170.0])]);
    mk("wallpaper_aurora", [[8.0, 20.0, 40.0], [20.0, 90.0, 110.0], [110.0, 230.0, 190.0]], &[(0.3, 0.25, 0.5, [140.0, 90.0, 255.0]), (0.8, 0.8, 0.5, [60.0, 255.0, 200.0])]);
    mk("wallpaper_ocean", [[6.0, 24.0, 58.0], [14.0, 70.0, 140.0], [90.0, 180.0, 230.0]], &[(0.7, 0.15, 0.5, [190.0, 235.0, 255.0]), (0.2, 0.85, 0.5, [10.0, 40.0, 110.0])]);
    mk("wallpaper_ember", [[28.0, 10.0, 18.0], [120.0, 34.0, 40.0], [250.0, 160.0, 70.0]], &[(0.2, 0.85, 0.55, [255.0, 210.0, 120.0]), (0.85, 0.2, 0.4, [150.0, 40.0, 90.0])]);
    mk("wallpaper_lilac", [[60.0, 50.0, 110.0], [150.0, 120.0, 200.0], [240.0, 200.0, 230.0]], &[(0.8, 0.2, 0.5, [255.0, 235.0, 250.0]), (0.15, 0.8, 0.5, [90.0, 100.0, 220.0])]);
    mk("wallpaper_graphite", [[16.0, 18.0, 24.0], [38.0, 42.0, 54.0], [88.0, 94.0, 110.0]], &[(0.75, 0.2, 0.55, [120.0, 130.0, 160.0]), (0.2, 0.9, 0.5, [50.0, 60.0, 90.0])]);
    // Cobalt Mist ships with the prototype: downscale it for the wasm bundle and derive the blurred glass backdrop.
    let src = std::env::var("WALLPAPER_SRC").unwrap_or("/tmp/wp_src.jpg".into());
    let img = image::open(&src).expect("wallpaper.jpg").to_rgb8();
    let big = imageops::resize(&img, 1600, 1000, imageops::FilterType::Lanczos3);
    save_jpg(&big, &a.join("wallpaper.jpg"), 80);
    let small = imageops::resize(&img, 480, 300, imageops::FilterType::Triangle);
    save_jpg(&imageops::blur(&small, 14.0), &a.join("wallpaper_blur.jpg"), 80);
    let tsrc = Path::new(&src).parent().unwrap().join("thumbs");
    fs::create_dir_all(a.join("thumbs")).unwrap();
    for e in fs::read_dir(tsrc).unwrap().flatten() {
        fs::copy(e.path(), a.join("thumbs").join(e.file_name())).unwrap();
    }
    println!("wallpapers + thumbs done");
}

fn save_jpg(img: &image::RgbImage, p: &Path, q: u8) {
    let f = fs::File::create(p).unwrap();
    let mut enc = image::codecs::jpeg::JpegEncoder::new_with_quality(f, q);
    enc.encode_image(img).unwrap();
}

// ───────────────────────────────────────────── bundle ─────────────────────────────────────────────

fn bundle() {
    use base64::Engine;
    let r = root();
    let wasm = r.join("target/wasm32-unknown-unknown/wasm/smart_desktop.wasm");
    let out = r.join("target/wb");
    let _ = fs::remove_dir_all(&out);
    let st = Command::new("wasm-bindgen")
        .args(["--target", "no-modules", "--no-typescript", "--out-dir"])
        .arg(&out)
        .arg(&wasm)
        .status()
        .expect("wasm-bindgen CLI not found");
    assert!(st.success());
    let bg = out.join("smart_desktop_bg.wasm");
    let opt = out.join("opt.wasm");
    // apt's binaryen is too old for the wasm features modern rustc emits, so the optimiser is opt-in (WASM_OPT=1)
    if std::env::var("WASM_OPT").is_ok() && Command::new("wasm-opt").args(["-Oz", "--all-features", "-o"]).arg(&opt).arg(&bg).status().map(|s| s.success()).unwrap_or(false) {
        fs::rename(&opt, &bg).unwrap();
    } else {
        eprintln!("wasm-opt unavailable/failed — embedding unoptimised wasm");
    }
    let glue = fs::read_to_string(out.join("smart_desktop.js")).unwrap().replace("</script", "<\\/script");
    let b64 = base64::engine::general_purpose::STANDARD.encode(fs::read(&bg).unwrap());
    let html = HTML.replace("{{GLUE}}", &glue).replace("{{WASM}}", &b64);
    let dest = r.join("../index.html");
    fs::write(&dest, html).unwrap();
    println!("wrote {} ({:.1} MB)", dest.canonicalize().unwrap().display(), fs::metadata(&dest).unwrap().len() as f64 / 1e6);
}

